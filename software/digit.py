# Build font mapping:
FONT_16SEG = {}
for char, bits in FONT_16SEG_RAW:
    FONT_16SEG[char] = [seg for i, seg in enumerate(SEGMENT_16_FONT_ORDER) if (bits >> i) & 1]

class Digit(LED_strip):
    def __init__(self, index=0):
        super().__init__(count=16)
        self.index = index
        for i, seg_name in enumerate(SEGMENT_16_ORDER):
            coords = DIGITUS16_COORDS.get(seg_name, [0.0, 0.0])
            self.LEDs[i].set_x(coords[0])
            self.LEDs[i].set_y(coords[1])
        self.width = x_digitus16
        self.height = y_digitus16

    def get_width(self):
        return self.width

    def extend_horiz(self, hops: int):
        for l in self.LEDs:
            l.set_x(l.get_x() + x_digitus16*hops)

    def get_height(self):
        return self.height

    def extend_vert(self, hops: int):
        for l in self.LEDs:
            l.set_y(l.get_y() + y_digitus16*hops)

    def turn_on(self):
        for l in self.LEDs:
            l.turn_on()

    def turn_off(self):
        for l in self.LEDs:
            l.turn_off()

    def set_fg(self, color):
        for l in self.LEDs:
            l.set_fg(color)

    def set_bg(self, color):
        for l in self.LEDs:
            l.set_bg(color)

    def set_char(self, ch):
        # Turn off all LEDs first
        for l in self.LEDs:
            l.turn_off()
        lit = FONT_16SEG.get(ch)
        if not lit:
            return
        for seg_name in lit:
            if seg_name in SEGMENT_16_ORDER:
                seg_index = SEGMENT_16_ORDER.index(seg_name)
                self.LEDs[seg_index].turn_on()

    def get_color(self):
        digit_color = {l.get_color() for l in self.LEDs}
        return digit_color
